-- Flashback v2.2 · Kho dữ liệu và cắt đề (IQX-Flashback-SPEC-DuLieu.md, thay thế v2 §5).
-- Additive and idempotent: no existing column is dropped or rewritten. The v1.x round tables, the
-- v2 room tables and every existing fb_matches row stay exactly as they were; the only change to
-- fb_matches is two nullable columns that new matches fill in.
--
--   fb_dataset_versions   one row per build of the dataset (building -> active | failed -> retired)
--   fb_dataset_symbols    one row per basket symbol of a version: ok, or excluded with a reason
--   fb_dataset_bars       the full adjusted daily history of every ok symbol, frozen at build time
--   fb_dataset_prefix     the cumulative arrays of §1.3 (one row per symbol) used to test a cut in O(1)
--   fb_matches            dataset_version + start_idx: which version and which cut a match used
--
-- Readers only ever look at the single `active` version. A new version is written completely under
-- status 'building' and becomes visible by one UPDATE inside one transaction, so no match can see a
-- half-old half-new dataset (spec §2.2 step 4).

-- 1. Versions. `version` is the number shown to admins and stored on matches.
CREATE TABLE IF NOT EXISTS fb_dataset_versions (
  version integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  status varchar(16) NOT NULL DEFAULT 'building',
  symbols_count integer NOT NULL DEFAULT 0,
  -- e.g. 'DNSE:x1000:adjusted'; several sources are joined with '+' when a fallback was used
  source varchar(160) NOT NULL DEFAULT '',
  -- {excluded: [{symbol, reason}], timings, basket, parameters ...}: the build log of §2.2 step 5
  log jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- 'scheduled' (job after the VN100 rebalance), 'manual' (admin button) or 'cli' (first build on deploy)
  trigger_kind varchar(16) NOT NULL DEFAULT 'scheduled',
  requested_by varchar(64),
  -- Written by the builder while it runs; a `building` row whose heartbeat is stale is an
  -- interrupted build and is marked failed by the next run.
  heartbeat_at timestamptz NOT NULL DEFAULT now(),
  progress jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Thresholds that are baked into the stored arrays (max_gap_sessions) and therefore belong to the version.
  params jsonb NOT NULL DEFAULT '{}'::jsonb,
  finished_at timestamptz,
  activated_at timestamptz,
  CONSTRAINT ck_fb_dataset_versions_status CHECK (status IN ('building', 'active', 'retired', 'failed')),
  CONSTRAINT ck_fb_dataset_versions_trigger CHECK (trigger_kind IN ('scheduled', 'manual', 'cli')),
  CONSTRAINT ck_fb_dataset_versions_symbols CHECK (symbols_count >= 0)
);
-- At most one active version and at most one build in flight, enforced by the database.
CREATE UNIQUE INDEX IF NOT EXISTS uq_fb_dataset_versions_one_active
  ON fb_dataset_versions ((1)) WHERE status = 'active';
CREATE UNIQUE INDEX IF NOT EXISTS uq_fb_dataset_versions_one_building
  ON fb_dataset_versions ((1)) WHERE status = 'building';
CREATE INDEX IF NOT EXISTS ix_fb_dataset_versions_created ON fb_dataset_versions (created_at DESC);

-- 2. Symbols of a version.
CREATE TABLE IF NOT EXISTS fb_dataset_symbols (
  version integer NOT NULL REFERENCES fb_dataset_versions(version) ON DELETE CASCADE,
  symbol varchar(16) NOT NULL,
  bars_count integer NOT NULL DEFAULT 0,
  first_date date,
  last_date date,
  status varchar(16) NOT NULL,
  -- Vietnamese reason shown to admins when the symbol is excluded, e.g. 'Chưa đủ lịch sử'.
  reason text,
  -- Source and unit of the prices, e.g. 'DNSE:x1000:adjusted'.
  price_source varchar(64),
  -- 'matched' = value_raw is the exchange's matched value for every bar; 'approx' = adjusted close x
  -- volume for every bar; 'mixed' = matched where the source had it, approximated elsewhere.
  value_basis varchar(16),
  bad_count integer NOT NULL DEFAULT 0,
  CONSTRAINT pk_fb_dataset_symbols PRIMARY KEY (version, symbol),
  CONSTRAINT ck_fb_dataset_symbols_status CHECK (status IN ('ok', 'excluded')),
  CONSTRAINT ck_fb_dataset_symbols_basis CHECK (value_basis IS NULL OR value_basis IN ('matched', 'mixed', 'approx')),
  CONSTRAINT ck_fb_dataset_symbols_count CHECK (bars_count >= 0 AND bad_count >= 0)
);
CREATE INDEX IF NOT EXISTS ix_fb_dataset_symbols_status ON fb_dataset_symbols (version, status);

-- 3. Bars: server-only. `date` never leaves the server while a match is being played.
--    Prices are integer VND (adjusted), volume as published by the vendor, value_raw in VND.
CREATE TABLE IF NOT EXISTS fb_dataset_bars (
  version integer NOT NULL,
  symbol varchar(16) NOT NULL,
  idx integer NOT NULL,
  date date NOT NULL,
  open bigint NOT NULL,
  high bigint NOT NULL,
  low bigint NOT NULL,
  close bigint NOT NULL,
  volume bigint NOT NULL,
  value_raw bigint NOT NULL,
  gap_before smallint NOT NULL DEFAULT 0,
  bad smallint NOT NULL DEFAULT 0,
  ret double precision NOT NULL DEFAULT 0,
  CONSTRAINT pk_fb_dataset_bars PRIMARY KEY (version, symbol, idx),
  CONSTRAINT fk_fb_dataset_bars_symbol FOREIGN KEY (version, symbol)
    REFERENCES fb_dataset_symbols(version, symbol) ON DELETE CASCADE,
  CONSTRAINT ck_fb_dataset_bars_idx CHECK (idx >= 0),
  CONSTRAINT ck_fb_dataset_bars_gap CHECK (gap_before >= 0),
  CONSTRAINT ck_fb_dataset_bars_bad CHECK (bad IN (0, 1))
);

-- 4. Cumulative arrays of §1.3, one row per symbol. X[k] is the sum over sessions 0..k-1, so each
--    array has n + 1 elements and the sum over [a, b) is X[b] - X[a]. `days` holds the session
--    dates as days since 1970-01-01 so the cut engine can test "12 months from today" without
--    loading the bars; p_gap is built with params.max_gap_sessions of its version.
CREATE TABLE IF NOT EXISTS fb_dataset_prefix (
  version integer NOT NULL,
  symbol varchar(16) NOT NULL,
  n integer NOT NULL,
  days integer[] NOT NULL,
  p_gap integer[] NOT NULL,
  p_bad integer[] NOT NULL,
  p_zero integer[] NOT NULL,
  p_val double precision[] NOT NULL,
  p_r double precision[] NOT NULL,
  p_r2 double precision[] NOT NULL,
  CONSTRAINT pk_fb_dataset_prefix PRIMARY KEY (version, symbol),
  CONSTRAINT fk_fb_dataset_prefix_symbol FOREIGN KEY (version, symbol)
    REFERENCES fb_dataset_symbols(version, symbol) ON DELETE CASCADE,
  CONSTRAINT ck_fb_dataset_prefix_length CHECK (
    n >= 0
    AND cardinality(days) = n
    AND cardinality(p_gap) = n + 1
    AND cardinality(p_bad) = n + 1
    AND cardinality(p_zero) = n + 1
    AND cardinality(p_val) = n + 1
    AND cardinality(p_r) = n + 1
    AND cardinality(p_r2) = n + 1
  )
);

-- 5. Which cut a match used (spec §3.5). NULL for matches created before this migration, which
--    keep their own copy of the bars in warmup_bars/bars; new matches fill both.
ALTER TABLE fb_matches ADD COLUMN IF NOT EXISTS dataset_version integer REFERENCES fb_dataset_versions(version);
ALTER TABLE fb_matches ADD COLUMN IF NOT EXISTS start_idx integer;
ALTER TABLE fb_matches DROP CONSTRAINT IF EXISTS ck_fb_matches_dataset_cut;
ALTER TABLE fb_matches
  ADD CONSTRAINT ck_fb_matches_dataset_cut CHECK (
    (dataset_version IS NULL) = (start_idx IS NULL) AND (start_idx IS NULL OR start_idx >= 0)
  );
CREATE INDEX IF NOT EXISTS ix_fb_matches_dataset
  ON fb_matches (dataset_version) WHERE dataset_version IS NOT NULL;

