COMMENT ON TABLE fb_dataset_versions IS 'Phiên bản kho dữ liệu Flashback v2.2; chỉ một phiên bản active, ván mới luôn cắt từ đó.';
COMMENT ON TABLE fb_dataset_symbols IS 'Mã VN100 của một phiên bản kho: ok hoặc excluded kèm lý do.';
COMMENT ON TABLE fb_dataset_bars IS 'Toàn bộ lịch sử phiên đã điều chỉnh của một mã, cố định từ lúc tạo kho. Chỉ server.';
COMMENT ON TABLE fb_dataset_prefix IS 'Mảng cộng dồn §1.3 của một mã (X[k] = tổng phiên 0..k-1) để kiểm tra điểm cắt trong thời gian không đổi.';
COMMENT ON COLUMN fb_matches.dataset_version IS 'Phiên bản kho mà ván đã cắt; NULL với ván tạo trước v2.2.';
COMMENT ON COLUMN fb_matches.start_idx IS 'Điểm cắt s: phiên đầu của 252 phiên khởi tạo trong bộ dữ liệu của mã.';
