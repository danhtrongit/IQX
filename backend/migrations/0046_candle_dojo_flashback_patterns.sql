-- Candle Dojo v1.3 · mẫu nến tính sẵn trong kho Flashback (IQX-Candle-Dojo-SPEC-v1.3-BoSung-MauNenTinhSan.md).
-- Additive and idempotent: only new tables. fb_dataset_versions, fb_dataset_symbols, fb_dataset_bars,
-- fb_dataset_prefix and fb_matches keep every column, type and key they have.
--
--   fb_dataset_patterns      the pattern ending at each session of each symbol (at most one row per session)
--   fb_dataset_pattern_runs  log of every "Tính mẫu nến" run (the newest `done` run of a version is the one used)
--   fb_dataset_raw           unadjusted prices and the exchange reference price, only for the 4 Vietnam cards
--   fb_match_cards           the cards shown to each player in each match ("Thẻ trong ván")

-- 1. Runs of the pattern step ("bước 2b"). One running run per dataset version at a time.
CREATE TABLE IF NOT EXISTS fb_dataset_pattern_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version integer NOT NULL REFERENCES fb_dataset_versions(version) ON DELETE CASCADE,
  detector_version integer NOT NULL,
  status varchar(12) NOT NULL DEFAULT 'running',
  -- 'build' (step 2b of a new dataset), 'backfill' (CLI on the active version), 'admin' (button), 'detector' (new detector)
  trigger_kind varchar(12) NOT NULL DEFAULT 'build',
  requested_by varchar(64),
  started_at timestamptz NOT NULL DEFAULT now(),
  heartbeat_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  symbols_done integer NOT NULL DEFAULT 0,
  symbols_total integer NOT NULL DEFAULT 0,
  patterns_count integer NOT NULL DEFAULT 0,
  -- {failed: [{symbol, reason}], raw: {...}, missing_raw_sessions, timings}: error codes and reasons
  log jsonb NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT ck_fb_dataset_pattern_runs_status CHECK (status IN ('running', 'done', 'failed')),
  CONSTRAINT ck_fb_dataset_pattern_runs_trigger CHECK (trigger_kind IN ('build', 'backfill', 'admin', 'detector')),
  CONSTRAINT ck_fb_dataset_pattern_runs_counts CHECK (symbols_done >= 0 AND symbols_total >= 0 AND patterns_count >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fb_dataset_pattern_runs_one_running
  ON fb_dataset_pattern_runs (version) WHERE status = 'running';
CREATE INDEX IF NOT EXISTS ix_fb_dataset_pattern_runs_version
  ON fb_dataset_pattern_runs (version, finished_at DESC NULLS LAST, id DESC);

-- 2. Patterns: the result of pick() at session `idx` (the LAST session of the pattern).
CREATE TABLE IF NOT EXISTS fb_dataset_patterns (
  version integer NOT NULL,
  symbol varchar(16) NOT NULL,
  idx integer NOT NULL,
  date date NOT NULL,
  card_id varchar(32) NOT NULL,
  card_n smallint NOT NULL,
  tier smallint NOT NULL,
  detector_version integer NOT NULL,
  CONSTRAINT pk_fb_dataset_patterns PRIMARY KEY (version, symbol, idx, detector_version),
  CONSTRAINT fk_fb_dataset_patterns_symbol FOREIGN KEY (version, symbol)
    REFERENCES fb_dataset_symbols(version, symbol) ON DELETE CASCADE,
  CONSTRAINT ck_fb_dataset_patterns_n CHECK (card_n BETWEEN 1 AND 20),
  CONSTRAINT ck_fb_dataset_patterns_tier CHECK (tier BETWEEN 1 AND 5),
  CONSTRAINT ck_fb_dataset_patterns_idx CHECK (idx >= card_n - 1)
);
CREATE INDEX IF NOT EXISTS ix_fb_dataset_patterns_date
  ON fb_dataset_patterns (version, symbol, date);
CREATE INDEX IF NOT EXISTS ix_fb_dataset_patterns_card
  ON fb_dataset_patterns (version, card_id);

-- 3. Raw prices for Limit Up Lock / Limit Down Lock / Limit Up Close / Limit Down Close (v1.3 §2.3).
--    Prices are integer VND exactly as the exchange published them (unadjusted).
CREATE TABLE IF NOT EXISTS fb_dataset_raw (
  version integer NOT NULL,
  symbol varchar(16) NOT NULL,
  idx integer NOT NULL,
  open_raw bigint NOT NULL,
  high_raw bigint NOT NULL,
  low_raw bigint NOT NULL,
  close_raw bigint NOT NULL,
  ref_price bigint NOT NULL,
  exchange varchar(8) NOT NULL DEFAULT 'HOSE',
  CONSTRAINT pk_fb_dataset_raw PRIMARY KEY (version, symbol, idx),
  CONSTRAINT fk_fb_dataset_raw_bar FOREIGN KEY (version, symbol, idx)
    REFERENCES fb_dataset_bars(version, symbol, idx) ON DELETE CASCADE,
  CONSTRAINT ck_fb_dataset_raw_exchange CHECK (exchange IN ('HOSE', 'HNX', 'UPCOM')),
  CONSTRAINT ck_fb_dataset_raw_prices CHECK (
    open_raw > 0 AND high_raw > 0 AND low_raw > 0 AND close_raw > 0 AND ref_price > 0
  )
);

-- 4. Cards shown to a player in a match: rebuilds "Thẻ trong ván" when the player re-enters or reviews.
CREATE TABLE IF NOT EXISTS fb_match_cards (
  match_id uuid NOT NULL REFERENCES fb_matches(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- Session 1..P of the match when the card appeared.
  play_idx integer NOT NULL,
  card_id varchar(32) NOT NULL,
  card_n smallint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pk_fb_match_cards PRIMARY KEY (match_id, user_id, play_idx),
  CONSTRAINT ck_fb_match_cards_play CHECK (play_idx >= 1),
  CONSTRAINT ck_fb_match_cards_n CHECK (card_n BETWEEN 1 AND 20)
);
CREATE INDEX IF NOT EXISTS ix_fb_match_cards_user ON fb_match_cards (user_id, created_at DESC);

COMMENT ON TABLE fb_dataset_patterns IS 'Mẫu nến tính sẵn (v1.3): tại phiên idx của một mã có mẫu card_id kết thúc ở đó. Tối đa một dòng mỗi phiên (pick).';
COMMENT ON TABLE fb_dataset_pattern_runs IS 'Nhật ký các lần tính mẫu nến của kho Flashback; lần done mới nhất của phiên bản được dùng.';
COMMENT ON TABLE fb_dataset_raw IS 'Giá gốc và giá tham chiếu của sàn, chỉ cho 4 thẻ trần/sàn Việt Nam. Không thêm cột vào fb_dataset_bars.';
COMMENT ON TABLE fb_match_cards IS 'Thẻ đã hiện cho từng người trong từng ván Flashback (khối Thẻ trong ván, nhãn Đã gặp).';
