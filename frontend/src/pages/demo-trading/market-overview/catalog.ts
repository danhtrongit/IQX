export function getWidgetMeta<W extends WidgetSlug>(slug: W): WidgetMeta<W> {
  return WIDGET_CATALOG[slug]
}

export function normalizeVi(str: string): string {
  return str
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[đĐ]/g, "d")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim()
}

export function matchesWidgetSearch(
  meta: WidgetMeta,
  groupLabel: string,
  query: string,
): boolean {
  const normalizedQuery = normalizeVi(query)
  if (!normalizedQuery) return true

  const haystack = normalizeVi([meta.title, groupLabel, ...meta.keywords].join(" "))
  return haystack.includes(normalizedQuery)
}

