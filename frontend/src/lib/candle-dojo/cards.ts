const BY_ID = new Map<string, CdCardDef>(CD_CARDS.map((card) => [card.id, card]));

export function cdCard(id: string): CdCardDef | undefined {
  return BY_ID.get(id);
}

export function cdCardPrice(card: Pick<CdCardDef, 'tier'>): number {
  return CD_TIER_INFO[card.tier].priceXu;
}

export function cdCardsOfLesson(lessonId: string): CdCardDef[] {
  return CD_CARDS.filter((card) => card.lessonId === lessonId);
}
