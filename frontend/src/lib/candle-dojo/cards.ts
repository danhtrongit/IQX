export type CdTier = 1 | 2 | 3 | 4 | 5;
export type CdCardContext = 'D' | 'T' | 'F';
/** Thẻ Việt Nam vẽ riêng: Limit Up Lock, Limit Down Lock, Limit Up Close, Limit Down Close. */
export type CdVnShape = 'lul' | 'ldl' | 'luc' | 'ldc';

export interface CdCardDef {
  readonly id: string;
  readonly name: string;
  readonly tier: CdTier;
  /** Bối cảnh cần có: D = sau nhịp giảm, T = sau nhịp tăng, F = bất kỳ. */
  readonly ctx: CdCardContext;
  /** 1 = tín hiệu tăng, -1 = giảm, 0 = trung tính (chỉ để chọn màu). */
  readonly dir: -1 | 0 | 1;
  /** Hình mẫu chuẩn, mỗi nến [mở, cao, thấp, đóng] theo đơn vị tương đối; null với thẻ Việt Nam. */
  readonly shape: readonly (readonly [number, number, number, number])[] | null;
  readonly vn: CdVnShape | null;
  /** Bài Candle Dojo dạy thẻ này; học xong bài là mua được thẻ. */
  readonly lessonId: string;
  readonly dojo: number;
  /** Số nến của mẫu (shape.length; thẻ Việt Nam là 1). */
  readonly candles: number;
}

